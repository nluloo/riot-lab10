namespace Server;

public class CarRentalDatabase
{
    public static readonly string[] ReplicatedTables = { "locations", "cars", "customers", "rentals" };

    public const string DefaultPrimaryConnectionString =
        "Host=127.0.0.1;Port=5433;Username=postgres;Password=postgres;Database=carrental;Timeout=5;Application Name=lab6-primary";

    public const string DefaultReplicaConnectionString =
        "Host=127.0.0.1;Port=5434;Username=postgres;Password=postgres;Database=carrental;Timeout=5;Application Name=lab6-replica";

    private const int HealthCheckTimeoutSeconds = 2;

    private const string SchemaSql = """
        CREATE TABLE IF NOT EXISTS locations (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            address TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS cars (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            brand TEXT NOT NULL,
            model TEXT NOT NULL,
            registration_number TEXT NOT NULL UNIQUE,
            location_id INTEGER NOT NULL REFERENCES locations (id),
            daily_price NUMERIC(10, 2) NOT NULL CHECK (daily_price > 0),
            is_available BOOLEAN NOT NULL
        );

        CREATE TABLE IF NOT EXISTS customers (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            full_name TEXT NOT NULL,
            phone TEXT NOT NULL UNIQUE
        );

        CREATE TABLE IF NOT EXISTS rentals (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            customer_id INTEGER NOT NULL REFERENCES customers (id),
            car_id INTEGER NOT NULL REFERENCES cars (id),
            start_date DATE NOT NULL,
            end_date DATE NOT NULL,
            status TEXT NOT NULL CHECK (status IN ('Active', 'Cancelled', 'Returned')),
            amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
            CHECK (end_date >= start_date)
        );

        CREATE TABLE IF NOT EXISTS replication_meta (
            id INTEGER PRIMARY KEY,
            lsn BIGINT NOT NULL,
            updated_at TIMESTAMPTZ NOT NULL
        );
        """;

    private const string MetaSeedSql = """
        INSERT INTO replication_meta (id, lsn, updated_at)
        VALUES (1, 0, NOW())
        ON CONFLICT (id) DO NOTHING;
        """;

    private const string SeedSql = """
        INSERT INTO locations (name, address) VALUES
            ('Минск', 'ул. Ленина, 10'),
            ('Брест', 'ул. Советская, 25');

        INSERT INTO cars (brand, model, registration_number, location_id, daily_price, is_available) VALUES
            ('Toyota', 'Camry', '1234 AB-7', 1, 120, TRUE),
            ('Volkswagen', 'Polo', '2345 BC-7', 1, 80, TRUE),
            ('Kia', 'Rio', '3456 CD-1', 2, 75, TRUE),
            ('Skoda', 'Octavia', '4567 DE-1', 2, 100, FALSE);
        """;

    private readonly string _connectionString;

    public CarRentalDatabase(string name, string? connectionString = null)
    {
        Name = name;
        _connectionString = string.IsNullOrWhiteSpace(connectionString)
            ? DefaultPrimaryConnectionString
            : connectionString;
    }

    public string Name { get; }

    public string ConnectionString => _connectionString;

    public void EnsureCreated()
    {
        var builder = new NpgsqlConnectionStringBuilder(_connectionString);
        string databaseName = builder.Database ?? throw new InvalidOperationException("В строке подключения не указана база данных");

        if (!Regex.IsMatch(databaseName, "^[a-z0-9_]+$"))
        {
            throw new InvalidOperationException("Некорректное имя базы данных");
        }

        builder.Database = "postgres";

        using (var admin = new NpgsqlConnection(builder.ConnectionString))
        {
            admin.Open();

            using var exists = new NpgsqlCommand("SELECT 1 FROM pg_database WHERE datname = @name", admin);
            exists.Parameters.AddWithValue("name", databaseName);

            if (exists.ExecuteScalar() == null)
            {
                using var create = new NpgsqlCommand($"CREATE DATABASE {databaseName}", admin);
                create.ExecuteNonQuery();
            }
        }

        using var connection = Open();

        using (var schema = new NpgsqlCommand(SchemaSql, connection))
        {
            schema.ExecuteNonQuery();
        }

        using (var meta = new NpgsqlCommand(MetaSeedSql, connection))
        {
            meta.ExecuteNonQuery();
        }

        using var count = new NpgsqlCommand("SELECT COUNT(*) FROM locations", connection);
        long locations = (long)(count.ExecuteScalar() ?? 0L);

        if (locations == 0)
        {
            using var seed = new NpgsqlCommand(SeedSql, connection);
            seed.ExecuteNonQuery();
        }
    }

    public long Reset()
    {
        using var connection = Open();
        using var transaction = connection.BeginTransaction();

        using (var truncate = CreateCommand(
                   connection,
                   transaction,
                   "TRUNCATE TABLE rentals, customers, cars, locations RESTART IDENTITY CASCADE"))
        {
            truncate.ExecuteNonQuery();
        }

        using (var seed = CreateCommand(connection, transaction, SeedSql))
        {
            seed.ExecuteNonQuery();
        }

        long lsn = BumpLsn(connection, transaction);
        transaction.Commit();

        return lsn;
    }

    public NpgsqlConnection Open()
    {
        var connection = new NpgsqlConnection(_connectionString);
        connection.Open();
        return connection;
    }

    public bool Ping()
    {
        try
        {
            var builder = new NpgsqlConnectionStringBuilder(_connectionString)
            {
                Timeout = HealthCheckTimeoutSeconds
            };

            using var connection = new NpgsqlConnection(builder.ConnectionString);
            connection.Open();

            using var command = new NpgsqlCommand("SELECT 1", connection)
            {
                CommandTimeout = HealthCheckTimeoutSeconds
            };

            command.ExecuteScalar();
            return true;
        }
        catch (Exception)
        {
            return false;
        }
    }

    public long GetLsn()
    {
        using var connection = Open();
        using var command = new NpgsqlCommand("SELECT lsn FROM replication_meta WHERE id = 1", connection);
        return Convert.ToInt64(command.ExecuteScalar() ?? 0L);
    }

    public long BumpLsn(NpgsqlConnection connection, NpgsqlTransaction? transaction)
    {
        using (var select = CreateCommand(
                   connection,
                   transaction,
                   "SELECT lsn FROM replication_meta WHERE id = 1 FOR UPDATE"))
        {
            long current = Convert.ToInt64(select.ExecuteScalar() ?? 0L);

            using var update = CreateCommand(
                connection,
                transaction,
                "UPDATE replication_meta SET lsn = @lsn, updated_at = NOW() WHERE id = 1");
            update.Parameters.AddWithValue("lsn", current + 1);
            update.ExecuteNonQuery();

            return current + 1;
        }
    }

    public long BumpLsn()
    {
        using var connection = Open();
        return BumpLsn(connection, null);
    }

    public void SetLsn(NpgsqlConnection connection, NpgsqlTransaction? transaction, long lsn)
    {
        using var command = CreateCommand(
            connection,
            transaction,
            "UPDATE replication_meta SET lsn = @lsn, updated_at = NOW() WHERE id = 1");
        command.Parameters.AddWithValue("lsn", lsn);

        if (command.ExecuteNonQuery() == 0)
        {
            using var insert = CreateCommand(
                connection,
                transaction,
                "INSERT INTO replication_meta (id, lsn, updated_at) VALUES (1, @lsn, NOW())");
            insert.Parameters.AddWithValue("lsn", lsn);
            insert.ExecuteNonQuery();
        }
    }

    public Car? GetCarByRegistration(string registrationNumber)
    {
        using var connection = Open();
        using var command = new NpgsqlCommand(
            """
            SELECT id, brand, model, registration_number, location_id, daily_price, is_available
            FROM cars
            WHERE LOWER(registration_number) = LOWER(@registration)
            """,
            connection);
        command.Parameters.AddWithValue("registration", registrationNumber);

        using var reader = command.ExecuteReader();
        return reader.Read() ? ReadCar(reader) : null;
    }

    public List<Car> SearchCars(string? location, string? brandOrModel)
    {
        using var connection = Open();
        using var command = new NpgsqlCommand(
            """
            SELECT c.id, c.brand, c.model, c.registration_number, c.location_id, c.daily_price, c.is_available
            FROM cars c
            JOIN locations l ON l.id = c.location_id
            WHERE c.is_available = TRUE
              AND (@location::text IS NULL OR l.name ILIKE '%' || @location || '%')
              AND (
                    @brand::text IS NULL
                    OR c.brand ILIKE '%' || @brand || '%'
                    OR c.model ILIKE '%' || @brand || '%'
                  )
            ORDER BY c.id
            """,
            connection);

        command.Parameters.Add(TextParameter("location", location));
        command.Parameters.Add(TextParameter("brand", brandOrModel));

        var cars = new List<Car>();
        using var reader = command.ExecuteReader();

        while (reader.Read())
        {
            cars.Add(ReadCar(reader));
        }

        return cars;
    }

    public int GetOrCreateCustomer(NpgsqlConnection connection, NpgsqlTransaction? transaction, string fullName, string phone)
    {
        using var command = CreateCommand(
            connection,
            transaction,
            """
            INSERT INTO customers (full_name, phone)
            VALUES (@name, @phone)
            ON CONFLICT (phone) DO UPDATE SET full_name = EXCLUDED.full_name
            RETURNING id
            """);

        command.Parameters.AddWithValue("name", fullName);
        command.Parameters.AddWithValue("phone", phone);
        return (int)(command.ExecuteScalar() ?? throw new InvalidOperationException("Не удалось сохранить клиента"));
    }

    public int InsertRental(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction,
        int customerId,
        int carId,
        DateTime startDate,
        DateTime endDate,
        decimal amount)
    {
        using var command = CreateCommand(
            connection,
            transaction,
            """
            INSERT INTO rentals (customer_id, car_id, start_date, end_date, status, amount)
            VALUES (@customerId, @carId, @startDate, @endDate, 'Active', @amount)
            RETURNING id
            """);

        command.Parameters.AddWithValue("customerId", customerId);
        command.Parameters.AddWithValue("carId", carId);
        command.Parameters.Add(new NpgsqlParameter("startDate", NpgsqlDbType.Date) { Value = startDate.Date });
        command.Parameters.Add(new NpgsqlParameter("endDate", NpgsqlDbType.Date) { Value = endDate.Date });
        command.Parameters.AddWithValue("amount", amount);
        return (int)(command.ExecuteScalar() ?? throw new InvalidOperationException("Не удалось создать аренду"));
    }

