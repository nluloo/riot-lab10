    public void UpsertRentals(NpgsqlConnection connection, NpgsqlTransaction transaction, IEnumerable<Rental> rows)
    {
        foreach (Rental row in rows)
        {
            using var command = CreateCommand(
                connection,
                transaction,
                """
                INSERT INTO rentals (id, customer_id, car_id, start_date, end_date, status, amount)
                VALUES (@id, @customerId, @carId, @startDate, @endDate, @status, @amount)
                ON CONFLICT (id) DO UPDATE SET
                    customer_id = EXCLUDED.customer_id,
                    car_id = EXCLUDED.car_id,
                    start_date = EXCLUDED.start_date,
                    end_date = EXCLUDED.end_date,
                    status = EXCLUDED.status,
                    amount = EXCLUDED.amount
                """);

            command.Parameters.AddWithValue("id", row.Id);
            command.Parameters.AddWithValue("customerId", row.CustomerId);
            command.Parameters.AddWithValue("carId", row.CarId);
            command.Parameters.Add(new NpgsqlParameter("startDate", NpgsqlDbType.Date) { Value = row.StartDate.Date });
            command.Parameters.Add(new NpgsqlParameter("endDate", NpgsqlDbType.Date) { Value = row.EndDate.Date });
            command.Parameters.AddWithValue("status", row.Status);
            command.Parameters.AddWithValue("amount", row.Amount);
            command.ExecuteNonQuery();
        }
    }

    /// Удалить строки, которых в источнике уже нет: репликация переносит не только изменения,
    /// но и удаления.
    public int DeleteMissing(NpgsqlConnection connection, NpgsqlTransaction transaction, string table, IEnumerable<int> existingIds)
    {
        EnsureKnownTable(table);

        using var command = CreateCommand(
            connection,
            transaction,
            $"DELETE FROM {table} WHERE NOT (id = ANY(@ids))");
        command.Parameters.AddWithValue("ids", existingIds.ToArray());

        return command.ExecuteNonQuery();
    }

    public void AlignSequences(NpgsqlConnection connection, NpgsqlTransaction transaction)
    {
        foreach (string table in ReplicatedTables)
        {
            using var command = CreateCommand(connection, transaction, $"""
                SELECT setval(
                    pg_get_serial_sequence('{table}', 'id'),
                    COALESCE((SELECT MAX(id) FROM {table}), 1),
                    (SELECT COUNT(*) FROM {table}) > 0)
                """);
            command.ExecuteScalar();
        }
    }

    private int Count(string sql)
    {
        using var connection = Open();
        using var command = new NpgsqlCommand(sql, connection);
        return (int)(long)(command.ExecuteScalar() ?? 0L);
    }

    private static void EnsureKnownTable(string table)
    {
        if (!ReplicatedTables.Contains(table))
        {
            throw new InvalidOperationException($"Неизвестная таблица {table}");
        }
    }

    private static NpgsqlCommand CreateCommand(
        NpgsqlConnection connection,
        NpgsqlTransaction? transaction,
        string sql,
        int commandTimeoutSeconds = 10)
    {
        var command = new NpgsqlCommand(sql, connection)
        {
            CommandTimeout = commandTimeoutSeconds
        };

        if (transaction != null)
        {
            command.Transaction = transaction;
        }

        return command;
    }

    private static NpgsqlParameter TextParameter(string name, string? value)
    {
        return new NpgsqlParameter(name, NpgsqlDbType.Text)
        {
            Value = string.IsNullOrWhiteSpace(value) ? DBNull.Value : value.Trim()
        };
    }

    private static Car ReadCar(NpgsqlDataReader reader)
    {
        return new Car
        {
            Id = reader.GetInt32(0),
            Brand = reader.GetString(1),
            Model = reader.GetString(2),
            RegistrationNumber = reader.GetString(3),
            LocationId = reader.GetInt32(4),
            DailyPrice = reader.GetDecimal(5),
            IsAvailable = reader.GetBoolean(6)
        };
    }

    private static Rental ReadRental(NpgsqlDataReader reader)
    {
        return new Rental
        {
            Id = reader.GetInt32(0),
            CustomerId = reader.GetInt32(1),
            CarId = reader.GetInt32(2),
            StartDate = reader.GetDateTime(3),
            EndDate = reader.GetDateTime(4),
            Status = reader.GetString(5),
            Amount = reader.GetDecimal(6)
        };
    }
