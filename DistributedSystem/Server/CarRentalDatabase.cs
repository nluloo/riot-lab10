    /// Перенос строк выполняется с явными id, чтобы обе копии содержали одинаковые записи.
    /// После переноса нужно выровнять последовательности: иначе INSERT в восстановленной копии
    /// выдаст id, который уже занят перенесённой строкой.
    public void UpsertLocations(NpgsqlConnection connection, NpgsqlTransaction transaction, IEnumerable<Location> rows)
    {
        foreach (Location row in rows)
        {
            using var command = CreateCommand(
                connection,
                transaction,
                """
                INSERT INTO locations (id, name, address)
                VALUES (@id, @name, @address)
                ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, address = EXCLUDED.address
                """);

            command.Parameters.AddWithValue("id", row.Id);
            command.Parameters.AddWithValue("name", row.Name);
            command.Parameters.AddWithValue("address", row.Address);
            command.ExecuteNonQuery();
        }
    }

    public void UpsertCars(NpgsqlConnection connection, NpgsqlTransaction transaction, IEnumerable<Car> rows)
    {
        foreach (Car row in rows)
        {
            using var command = CreateCommand(
                connection,
                transaction,
                """
                INSERT INTO cars (id, brand, model, registration_number, location_id, daily_price, is_available)
                VALUES (@id, @brand, @model, @registration, @locationId, @price, @isAvailable)
                ON CONFLICT (id) DO UPDATE SET
                    brand = EXCLUDED.brand,
                    model = EXCLUDED.model,
                    registration_number = EXCLUDED.registration_number,
                    location_id = EXCLUDED.location_id,
                    daily_price = EXCLUDED.daily_price,
                    is_available = EXCLUDED.is_available
                """);

            command.Parameters.AddWithValue("id", row.Id);
            command.Parameters.AddWithValue("brand", row.Brand);
            command.Parameters.AddWithValue("model", row.Model);
            command.Parameters.AddWithValue("registration", row.RegistrationNumber);
            command.Parameters.AddWithValue("locationId", row.LocationId);
            command.Parameters.AddWithValue("price", row.DailyPrice);
            command.Parameters.AddWithValue("isAvailable", row.IsAvailable);
            command.ExecuteNonQuery();
        }
    }

