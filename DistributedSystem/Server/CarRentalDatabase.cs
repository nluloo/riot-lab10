    }

    public List<RentalView> GetRentals()
    {
        using var connection = Open();
        using var command = new NpgsqlCommand(
            """
            SELECT r.id, cu.full_name, c.registration_number, r.start_date, r.end_date, r.status, r.amount
            FROM rentals r
            JOIN customers cu ON cu.id = r.customer_id
            JOIN cars c ON c.id = r.car_id
            ORDER BY r.id
            """,
            connection);

        var rentals = new List<RentalView>();
        using var reader = command.ExecuteReader();

        while (reader.Read())
        {
            rentals.Add(new RentalView
            {
                Id = reader.GetInt32(0),
                Customer = reader.GetString(1),
                RegistrationNumber = reader.GetString(2),
                StartDate = reader.GetDateTime(3),
                EndDate = reader.GetDateTime(4),
                Status = reader.GetString(5),
                Amount = reader.GetDecimal(6)
            });
        }

        return rentals;
    }

