-- Схема одного экземпляра данных. Этот же скрипт поднимает и Primary, и Replica,
-- поэтому начальное состояние двух копий совпадает (одинаковые id и значения).
--
-- Тесты (Tests/TestRig.cs) работают на базе carrental_test, чтобы не затирать демо-данные
-- стенда. CREATE DATABASE нельзя обвернуть в IF NOT EXISTS (не внутри транзакции),
-- поэтому \gexec: команда формируется только если базы ещё нет.
SELECT 'CREATE DATABASE carrental_test'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'carrental_test')\gexec

CREATE TABLE IF NOT EXISTS locations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    address TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS cars (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand TEXT NOT NULL,
    model TEXT NOT NULL,
    registration_number TEXT NOT NULL UNIQUE,
    location_id INTEGER NOT NULL REFERENCES locations (id),
    daily_price NUMERIC(10, 2) NOT NULL CHECK (daily_price > 0),
    is_available BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    phone TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS rentals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers (id),
    car_id INTEGER NOT NULL REFERENCES cars (id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('Active', 'Cancelled', 'Returned')),
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    CHECK (end_date >= start_date)
);

-- Версия данных экземпляра. Репликация передаёт изменения и переносит lsn в Replica,
-- по отставанию lsn видно, что копия не согласована.
CREATE TABLE IF NOT EXISTS replication_meta (
    id INTEGER PRIMARY KEY,
    lsn BIGINT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

